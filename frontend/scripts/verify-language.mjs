import { chromium, expect } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const output = resolve('../docs/screenshots')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
const page = await context.newPage()
const errors = []
let analysisSubmissions = 0
page.on('pageerror', error => errors.push(error.message))
page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/analyses') analysisSubmissions++ })
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.getByRole('textbox', { name: 'Research topic' }).fill('GLP-1')
await page.getByRole('button', { name: '切换为中文' }).click()
await expect(page.getByRole('heading', { level: 1 })).toContainText('智能分析')
await expect(page.getByRole('textbox', { name: '研究主题' })).toHaveValue('GLP-1')
await expect(page.getByRole('button', { name: '开始分析', exact: true })).toBeVisible()
await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN')
await page.screenshot({ path: resolve(output, 'home-chinese.png'), fullPage: true })
await page.getByRole('button', { name: '阿尔茨海默病', exact: true }).click()
await expect(page.getByRole('textbox', { name: '研究主题' })).toHaveValue("Alzheimer's Disease")
await page.getByRole('button', { name: '打开示例演示', exact: true }).click()
await page.locator('.analysis-complete').filter({ hasText: '分析完成' }).waitFor()
await expect(page.getByRole('heading', { name: '历年发文趋势' })).toBeVisible()
await expect(page.getByRole('heading', { name: 'AI 科研简报' })).toBeVisible()
await expect(page.locator('.status-badge')).toHaveText('缓存演示数据')
await expect(page.getByRole('img', { name: /^年度发文数量/ })).toBeVisible()
const analysisUrl = page.url()
const title = await page.locator('.paper-title').first().innerText()
const total = await page.locator('.kpi > strong').first().innerText()
await page.getByLabel('排序方式').selectOption('year')
await page.getByRole('button', { name: '查看前 100 篇' }).click()
await expect(page.locator('.papers-table tbody tr')).toHaveCount(100)
await page.getByRole('button', { name: 'Switch to English' }).click()
await expect(page.getByRole('heading', { name: 'Publications over time' })).toBeVisible()
await expect(page.getByLabel('Sort by')).toHaveValue('year')
await expect(page.locator('.papers-table tbody tr')).toHaveCount(100)
await expect(page.locator('.kpi > strong').first()).toHaveText(total)
await expect(page).toHaveURL(analysisUrl)
await page.getByLabel('Sort by').selectOption('impact_factor')
await expect(page.locator('.paper-title').first()).toHaveText(title)
await page.getByRole('button', { name: 'Show top 10' }).click()
await page.getByRole('button', { name: '切换为中文' }).click()
if (analysisSubmissions !== 1) throw new Error('Switching languages submitted another analysis')
await page.evaluate(() => window.scrollTo(0, 0))
await page.screenshot({ path: resolve(output, 'dashboard-chinese.png'), fullPage: true })
await page.getByRole('link', { name: '查看数据来源', exact: true }).click()
await page.getByRole('heading', { name: '数据采集记录' }).waitFor()
await expect(page.getByRole('heading', { name: '如何理解分析结果' })).toBeVisible()
await expect(page.locator('.methods-grid article').first()).toContainText('文献总量与全量年度计数来自 ESearch')
await expect(page.locator('.source-record')).toContainText('500 篇论文')
await expect(page.locator('.source-record')).toContainText('北京时间')
await page.screenshot({ path: resolve(output, 'data-sources-chinese.png'), fullPage: true })
await page.reload({ waitUntil: 'networkidle' })
await expect(page.getByRole('heading', { name: '数据来源与分析方法' })).toBeVisible()
await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN')
await page.goto(analysisUrl, { waitUntil: 'networkidle' })
await page.setViewportSize({ width: 390, height: 844 })
await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth, undefined, { timeout: 5000 })
await page.evaluate(() => scrollTo(0, 0))
await expect(page.getByRole('button', { name: 'Switch to English' })).toBeVisible()
await page.screenshot({ path: resolve(output, 'mobile-chinese.png') })
await page.getByRole('button', { name: 'Switch to English' }).click()
await expect(page.getByRole('link', { name: 'Data sources', exact: true })).toBeVisible()
await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth, undefined, { timeout: 5000 })
await page.getByRole('button', { name: '切换为中文' }).click()
await page.goto('http://127.0.0.1:5173/about', { waitUntil: 'networkidle' })
await expect(page.getByRole('heading', { name: '从文献出发，理解科研全景。' })).toBeVisible()
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.route('**/api/analyses', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'The request could not be completed. Please check your input and retry.' }) }))
await page.getByRole('textbox', { name: '研究主题' }).fill('CRISPR')
await page.getByRole('button', { name: '开始分析', exact: true }).click()
await expect(page.getByRole('alert')).toHaveText('请求未能完成，请检查输入后重试。')
await page.getByRole('button', { name: 'Switch to English' }).click()
await expect(page.getByRole('alert')).toHaveText('The request could not be completed. Please check your input and retry.')
await page.unroute('**/api/analyses')
await browser.close()
const report = { errors, checks: ['home translation', 'query preserved', 'translated suggestion retains real query', 'dashboard and chart labels', 'no new analysis on switch', 'paper data preserved', 'sort and expansion preserved', 'sources and methodology translated', 'reload persistence', 'Chinese and English mobile overflow', 'about translation', 'error translation in both directions'] }
await writeFile(resolve('../.impeccable/review/language-report.json'), JSON.stringify(report, null, 2))
console.log(JSON.stringify(report, null, 2))
if (errors.length) process.exitCode = 1
